export const LANGS = ['ar', 'en'];
export const DEFAULT_LANG = 'ar';

let current = DEFAULT_LANG;

/** The language in use: 'ar' | 'en'. */
export const getLang = () => current;

/** Set the language for t() (no DOM changes). */
export function setLanguage(lang) {
  current = LANGS.includes(lang) ? lang : DEFAULT_LANG;
}

/** Translate a key, filling {placeholders}. Falls back to English, then the key. */
export function t(key, params = {}) {
  const s = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? `{${k}}`));
}

/** Locale for Intl / toLocale*String: Arabic words with Western digits. */
export const locale = () => (current === 'ar' ? 'ar-EG-u-nu-latn' : 'en');

const LRI = String.fromCharCode(0x2066);
const PDI = String.fromCharCode(0x2069);

/**
 * Keep a left-to-right fragment (times like "13:00–13:30", domains) in its
 * order inside right-to-left text. Without this, "13:00–13:30" shows as
 * "13:30–13:00" in Arabic.
 */
export const ltr = (s) => `${LRI}${s}${PDI}`;

const RLI = String.fromCharCode(0x2067);

/**
 * Text placed inside a left-to-right context (the chart's SVG): in Arabic,
 * isolate it as right-to-left so "1 س 30 د" doesn't come out scrambled.
 */
export const inLtrContext = (s) => (current === 'ar' ? `${RLI}${s}${PDI}` : s);

// ---------------------------------------------------------------------------
// Pages

/** Fill [data-i18n] text and data-i18n-placeholder / -aria-label / -title attributes. */
export function translatePage(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const attr of ['placeholder', 'aria-label', 'title']) {
    for (const el of root.querySelectorAll(`[data-i18n-${attr}]`)) el.setAttribute(attr, t(el.dataset[`i18n${attr === 'aria-label' ? 'AriaLabel' : attr[0].toUpperCase() + attr.slice(1)}`]));
  }
}

/** Set <html lang dir> for the current language. */
export function applyDirection() {
  document.documentElement.lang = current;
  document.documentElement.dir = current === 'ar' ? 'rtl' : 'ltr';
}

/**
 * For extension pages: read settings.lang, set direction, translate the page.
 * Resolves once done, so pages can render their dynamic text afterwards.
 * Reloads the page when the language is changed elsewhere.
 */
export async function initPageLanguage() {
  const { settings } = await chrome.storage.local.get('settings');
  setLanguage(settings?.lang);
  applyDirection();
  translatePage();
  chrome.storage.onChanged.addListener((changes, area) => {
    if (area !== 'local' || !changes.settings) return;
    const next = changes.settings.newValue?.lang;
    if ((LANGS.includes(next) ? next : DEFAULT_LANG) !== current) location.reload();
  });
  return current;
}

/** Switch the language (stored with the other appearance choices). */
export async function toggleLanguage() {
  const { settings = {} } = await chrome.storage.local.get('settings');
  await chrome.storage.local.set({ settings: { ...settings, lang: current === 'ar' ? 'en' : 'ar' } });
}
